#!/usr/bin/env node
// One-shot package rename: old workspace names -> @selvajs/* scope.
// Safe to delete after the rename is committed.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const DRY_RUN = process.argv.includes('--dry-run');

// Order matters: longer/more specific names first so we never partially match.
// IMPORTANT: `@selvajs/compute` (external published pkg) is NOT renamed.
// IMPORTANT: `selva-compute-app` MUST be replaced before any pattern that could
// touch `@selvajs/compute`. We don't replace `@selvajs/compute` at all, so just be
// sure the `selva-compute-app` regex doesn't include a trailing-anchor that
// would match `@selvajs/compute` alone.
const replacements = [
  // Scoped @selva/* -> @selvajs/*
  ['@selva/supabase-provider', '@selvajs/supabase-provider'],
  ['@selva/builder-app', '@selvajs/builder-app'],
  ['@selva/platform', '@selvajs/platform'],
  ['@selva/schemas', '@selvajs/schemas'],
  ['@selva/config', '@selvajs/config'],
  // Unscoped -> @selvajs/*
  ['selva-compute-app', '@selvajs/compute-app'],
  ['selva-local-provider', '@selvajs/local-provider'],
  ['selva-shared', '@selvajs/shared'],
];

// File extensions to process
const exts = new Set([
  '.ts', '.tsx', '.js', '.mjs', '.cjs', '.svelte',
  '.json', '.jsonc',
  '.md', '.mdx',
  '.yml', '.yaml', '.toml',
  '.sql', '.css',
  '.cs', // .NET source — only if it actually mentions these names
  '.html'
]);

// Directories to skip
const skipDirs = new Set([
  'node_modules', '.git', '.svelte-kit', 'dist', 'build', '.turbo',
  '.changeset', // changeset markdowns will be regenerated; leave them
  'coverage', '.next', '.cache',
  'EmbeddedAssets', // built artifacts in Plugin/
  'bin', 'obj', // .NET build output
]);

// Files to skip explicitly
const skipFiles = new Set([
  'pnpm-lock.yaml', // regenerated by pnpm install
  'package-lock.json',
  'yarn.lock',
  'rename-packages.js', // this script itself (contains the mapping table)
]);

let filesScanned = 0;
let filesChanged = 0;
let totalReplacements = 0;

function shouldSkipPath(p) {
  const base = path.basename(p);
  if (skipFiles.has(base)) return true;
  return false;
}

function processFile(filePath) {
  const ext = path.extname(filePath);
  if (!exts.has(ext)) return;
  if (shouldSkipPath(filePath)) return;
  filesScanned++;

  let content;
  try {
    content = fs.readFileSync(filePath, 'utf8');
  } catch {
    return;
  }

  let updated = content;
  let fileReps = 0;

  for (const [oldName, newName] of replacements) {
    // Use a regex with negative lookbehind/lookahead to avoid partial-word matches
    // Need to escape special chars in oldName
    const escaped = oldName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    // Match boundary: not preceded by alphanumeric/dash/slash/at, not followed by
    // alphanumeric/dash. Special-case: an `@` already starts the scoped name, so
    // we just need to ensure we don't extend RIGHT past the end.
    const pattern = new RegExp(
      `(?<![A-Za-z0-9_\\-/@])${escaped}(?![A-Za-z0-9_\\-])`,
      'g'
    );
    const before = updated;
    updated = updated.replace(pattern, newName);
    if (updated !== before) {
      const matches = before.match(pattern);
      fileReps += matches ? matches.length : 0;
    }
  }

  if (updated !== content) {
    filesChanged++;
    totalReplacements += fileReps;
    if (DRY_RUN) {
      console.log(`would change (${fileReps}): ${path.relative(rootDir, filePath)}`);
    } else {
      fs.writeFileSync(filePath, updated, 'utf8');
      console.log(`changed (${fileReps}): ${path.relative(rootDir, filePath)}`);
    }
  }
}

function walk(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (skipDirs.has(entry.name)) continue;
      walk(full);
    } else if (entry.isFile()) {
      processFile(full);
    }
  }
}

console.log(DRY_RUN ? '=== DRY RUN ===' : '=== APPLYING RENAME ===');
walk(rootDir);
console.log('');
console.log(`Scanned ${filesScanned} files`);
console.log(`Changed ${filesChanged} files`);
console.log(`Total replacements: ${totalReplacements}`);
