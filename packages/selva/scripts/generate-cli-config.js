#!/usr/bin/env node
// Bundle the config manifest and the pure logic over it into the CLI, which
// ships without dependencies. Run after changing a setting in any slice:
//   pnpm --filter @selvajs/selva generate:cli-config
// A test in this package fails when the bundled copy is out of date.

import { build } from 'vite';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '../../cli/src/generated');

await build({
	configFile: false,
	logLevel: 'warn',
	resolve: { conditions: ['selva-source', 'node', 'import'] },
	ssr: { noExternal: true, resolve: { conditions: ['selva-source', 'node', 'import'] } },
	build: {
		ssr: resolve(here, '../src/lib/server/config/cli-entry.ts'),
		outDir,
		emptyOutDir: false,
		minify: false,
		target: 'node24',
		rollupOptions: {
			external: [/^node:/],
			output: {
				entryFileNames: 'config.js',
				format: 'es',
				banner: '// GENERATED by packages/selva/scripts/generate-cli-config.js. Do not edit.'
			}
		}
	}
});
console.log('✓ packages/cli/src/generated/config.js');
