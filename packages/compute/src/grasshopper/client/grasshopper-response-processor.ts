import { downloadFileData } from '@/core/files/handle-files';
import { FileBaseInfo } from '@/core/files/types';

import { GrasshopperComputeResponse } from '../types';

import {
	extractFileData,
	getValue,
	getValues,
	GetValuesOptions,
	GetValuesResult,
	ParsedContext
} from '../io/output/response-processors';

/** Reads parsed values and produced files out of one compute response. */
export default class GrasshopperResponseProcessor {
	constructor(
		/** Hand it to a mesh parser such as `@selvajs/visualization/parse`. */
		public readonly response: GrasshopperComputeResponse,
		/** Not read by this class; pass `debug` to the `@selvajs/visualization/parse` parser instead. */
		public readonly debug: boolean = false
	) {}

	/**
	 * Extract all values in the response.
	 *
	 * @typeParam T - Expected structure of the return value. Defaults to a simple key/value map. (later cast as needed)
	 * @param byId - Key by parameter ID instead of name. Requires the VektorNode rhino.compute branch.
	 * @param options - Controls parsing behavior such as Rhino geometry decoding.
	 * @returns Parsed Grasshopper output values.
	 *
	 * @example
	 * ```ts
	 * const processor = new GrasshopperResponseProcessor(response);
	 * const { values } = processor.getValues();
	 * ```
	 *
	 */
	public getValues<T = ParsedContext>(
		byId: boolean = false,
		options: GetValuesOptions = {}
	): GetValuesResult<T> {
		return getValues<T>(this.response, byId, options);
	}

	/**
	 * Retrieve a specific value by parameter name or ID.
	 *
	 * @param selector - `{ byName }` for the human-readable name, `{ byId }` for the parameter GUID.
	 * @param options - Parsing configuration (e.g. disable parsing or enable Rhino).
	 * @returns Single parsed value, array of values, or undefined if the parameter is absent.
	 *
	 * `byId` requires the VektorNode rhino.compute branch.
	 *
	 * @example
	 * ```ts
	 * const schema = processor.getValue({ byName: 'Schema' });
	 * const output = processor.getValue({ byId: 'a4be1c1e-23f9-4c27-b942-7f3bb2c45c6f' });
	 * ```
	 */
	public getValue(
		selector: { byName: string } | { byId: string },
		options?: GetValuesOptions
	): any {
		return getValue(this.response, selector, options);
	}

	/**
	 * Download all files generated by Grasshopper, optionally including
	 * additional user-provided files.
	 *
	 * Files are grouped under the specified folder name when downloaded.
	 *
	 * @param folderName - Name for the download directory.
	 * @param additionalFiles - Extra files to package (single file, array, or null).
	 *
	 * @example
	 * ```ts
	 * await processor.getAndDownloadFiles('gh-output');
	 * ```
	 *
	 * @example
	 * ```ts
	 * const extra = { name: 'notes.txt', data: 'Example' };
	 * await processor.getAndDownloadFiles('project', extra);
	 * ```
	 */
	public async getAndDownloadFiles(
		folderName: string,
		additionalFiles?: FileBaseInfo[] | FileBaseInfo | null
	): Promise<void> {
		await downloadFileData(extractFileData(this.response), folderName, additionalFiles);
	}
}
